import assert from 'node:assert/strict';
import {clipRange,videoEditPlan,isVideoFile} from '../lib/video-edit-plan.ts';
let count=0;const check=(value)=>{assert.ok(value);count++;};
const landscape={duration:180,width:1920,height:1080};
check(clipRange(180).end===60);
check(clipRange(180,80,170).start===80&&clipRange(180,80,170).end===140);
check(clipRange(15).end===15);
check(clipRange(180,-10,30).start===0);
const plan=videoEditPlan(landscape,{start:70,end:130});
check(plan.width===1280&&plan.height===720);
check(plan.duration===60&&plan.estimatedBytes<20*1024*1024);
const portrait=videoEditPlan({duration:90,width:1080,height:1920},{start:10,end:40});
check(portrait.width===720&&portrait.height===1280);
const small=videoEditPlan(landscape,{start:0,end:60},'small');
check(small.estimatedBytes<plan.estimatedBytes);
const muted=videoEditPlan(landscape,{start:0,end:60},'balanced',true);
check(muted.audioBitrate===0&&muted.estimatedBytes<plan.estimatedBytes);
const limited=videoEditPlan(landscape,{start:0,end:60},'balanced',false,3*1024*1024);
check(limited.estimatedBytes<3*1024*1024&&limited.videoBitrate<plan.videoBitrate);
assert.throws(()=>videoEditPlan(landscape,{start:0,end:61}));count++;
assert.throws(()=>videoEditPlan(landscape,{start:200,end:220}));count++;
assert.throws(()=>videoEditPlan(landscape,{start:0,end:60},'balanced',false,1000));count++;
check(isVideoFile({name:'CAMARA.MOV',type:''}));
check(!isVideoFile({name:'foto.jpg',type:'image/jpeg'}));
console.log(`${count} video editing plan checks passed.`);
